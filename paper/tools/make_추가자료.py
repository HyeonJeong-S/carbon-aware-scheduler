def math(doc, text):
    """식 한 줄 — 본편과 같은 Cambria Math 로 찍고 _·^ 를 진짜 첨자로 올린다.

    2026-09-24 사용자 메모(추가자료 식 (1)에 달림): "압축본에 있는 공식과 똑같은
    글씨체로 하는 것이 좋을듯,, 둘이 달라보여."  본편 식은 OMML 이라 Cambria Math
    로 조판되는데 여기는 Menlo 고정폭이어서 같은 식이 딴 글씨로 보였다.
    OMML 을 여기서 다시 짜는 것은 과하므로, **같은 서체 + 진짜 첨자**까지만 맞춘다
    (분수·적분 기호의 쌓임은 본편만 한다 — 여기 식은 전부 한 줄 형태다).
    """
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.6)
    p.paragraph_format.space_before = Pt(5)
    p.paragraph_format.space_after = Pt(5)

    def emit(t, kind):
        if not t:
            return
        r = p.add_run(t)
        r.font.name = "Cambria Math"
        r.font.size = Pt(9)
        if kind == "sub":
            r.font.subscript = True
        elif kind == "sup":
            r.font.superscript = True

    i = 0
    buf = ""
    while i < len(text):
        c = text[i]
        if c in "_^" and i + 1 < len(text):
            kind = "sub" if c == "_" else "sup"
            j = i + 1
            if text[j] == "{":
                depth = 1
                j += 1
                start = j
                while j < len(text) and depth:
                    if text[j] == "{":
                        depth += 1
                    elif text[j] == "}":
                        depth -= 1
                    j += 1
                chunk = text[start:j - 1]
            else:
                start = j
                # 중괄호가 없으면 이어지는 영숫자·프라임까지가 첨자다
                while j < len(text) and (text[j].isalnum() or text[j] == "′"):
                    j += 1
                chunk = text[start:j]
            # 중괄호 안에 또 _ 가 있으면(∫_{τ_j}^{τ_j+d_j} 처럼) 워드는 첨자를
            # 두 겹으로 못 올린다. 안쪽 _ 는 떼고 한 겹으로 찍는다.
            chunk = chunk.replace("_", "")
            emit(buf, "n"); buf = ""
            emit(chunk, kind)
            i = j
            continue
        buf += c
        i += 1
    emit(buf, "n")
    return p


def caption(doc, text):
    """표 설명. 본편과 섞이지 않도록 S 번호를 쓴다.

    2026-09-24: 본편은 캡션을 표 **위**에 둔다. 추가자료만 아래에 두고 있었고,
    table() 이 남기는 빈 문단 때문에 표에서 멀찍이 떨어져 다음 문단에 붙은 것처럼
    보였다. 위로 올리고 표와의 간격을 좁힌다.
    """
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(2)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.font.size = Pt(8.5)
    r.bold = True
    return p


def table(doc, rows, widths=None):
    """표를 만든다. 머리행은 쪽을 넘을 때마다 반복되게 한다.

    2026-09-24(73 지적): 표 S8 이 11쪽에서 머리행 + 한 줄만 나오고 12쪽에
    나머지 다섯 줄이 머리행 없이 이어졌다. 12쪽만 펴면 어느 열이 무슨 값인지
    알 수 없다. python-docx 에 없는 기능이라 XML 로 <w:tblHeader/> 를 넣는다.
    행이 쪽 경계에서 반으로 갈리는 것도 <w:cantSplit/> 로 막는다.
    """
    from docx.oxml.ns import qn
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    for ri, row in enumerate(t.rows):
        trPr = row._tr.get_or_add_trPr()
        trPr.append(trPr.makeelement(qn('w:cantSplit'), {}))
        if ri == 0:
            trPr.append(trPr.makeelement(qn('w:tblHeader'), {}))
    for i, row in enumerate(rows):
        for j, cell in enumerate(row):
            c = t.cell(i, j)
            c.text = ""
            p = c.paragraphs[0]
            r = p.add_run(str(cell))
            r.font.size = Pt(8.5)
            r.bold = (i == 0)
            # 숫자 열만 오른쪽으로 — 글로 된 열을 오른쪽에 붙이면 읽기 어렵다
            val = str(rows[-1][j]) if len(rows) > 1 else ""
            if j > 0 and re.match(r"^[\d,.\s%kgms건회배]+$", val):
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    doc.add_paragraph()
    return t



