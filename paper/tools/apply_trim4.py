    n0 = len(D.paragraphs(xml))
    before = sum(len(t) for *_, t in D.paragraphs(xml) if t)
    for head, new in EDITS:
        xml, o, n = D.replace_text(xml, head, new)
        print(f"  {o:>4} → {n:>4}자 ({n-o:+5})  {head[:30]}…")
